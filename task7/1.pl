% --- Служебные правила и работа с динамической базой фактов ---

свойство(Арг, Арг2) :- верно(Арг, Арг2), !.
свойство(Арг, Арг2) :-
    \+ ложно(Арг, Арг2),
    узнать(Арг, Арг2, Ответ),
    Ответ = да.

нет_свойства(Арг, Арг2) :- ложно(Арг, Арг2), !.
нет_свойства(Арг, Арг2) :-
    \+ верно(Арг, Арг2),
    узнать(Арг, Арг2, Ответ),
    Ответ = нет.

узнать(Арг, Арг2, Ответ) :-
    write(Арг), write(" "), write(Арг2), write("? (да./нет.): "),
    flush_output,
    прочитать_ответ(Ответ),
    запомнить(Арг, Арг2, Ответ).

прочитать_ответ(Ответ) :-
    read(Ввод),
    (   Ввод == end_of_file -> nl, writeln("Ввод прерван."), очистить, abort
    ;   (Ввод == да ; Ввод == нет) -> Ответ = Ввод
    ;   writeln("Пожалуйста, введите 'да.' или 'нет.' (с точкой в конце)."),
        прочитать_ответ(Ответ)
    ).

запомнить(Арг, Арг2, да) :- assert(верно(Арг, Арг2)).
запомнить(Арг, Арг2, нет) :- assert(ложно(Арг, Арг2)).

очистить :- retract(верно(_, _)), fail.
очистить :- retract(ложно(_, _)), fail.
очистить.
