% Главная точка входа
цель :-
    очистить,
    заболевание(Арг), !,
    nl,
    write("Предполагаемое заболевание: "), writeln(Арг),
    вывести_рекомендацию(Арг),
    очистить.
цель :-
    nl,
    writeln("К сожалению, по указанным симптомам заболевание определить не удалось."),
    writeln("ВАЖНО: при ухудшении состояния (отказ от воды, одышка, судороги, кровотечение, резкая слабость) немедленно обратитесь к ветеринарному врачу."),
    очистить.

